"""Accuracy and performance evaluation of the duplicate detector.

    python -m q2_duplicate_questions.evaluate          # writes examples/q2/EVALUATION.md

A) Section-6 corpus, inserted in order: each question checked against those before it.
B) Held-out labelled candidates checked against the full corpus.
   Reports exact-label accuracy plus duplicate precision/recall where
   "flagged" = exact/semantic duplicate or needs_review.
C) Latency: end-to-end check() on a bank of synthetic questions and raw vector
   search time at 100k vectors.
"""
from __future__ import annotations

import itertools
import time
from collections import Counter
from pathlib import Path

import numpy as np

from .core import Question, QuestionBank, SentenceTransformerEmbedder, TfidfEmbedder
from .data import CORPUS, HELD_OUT
from .detector import DuplicateDetector

LABELS = ["exact_duplicate", "semantic_duplicate", "needs_review", "unique"]


def corpus_bank(embedder) -> QuestionBank:
    bank = QuestionBank(embedder)
    for qid, text, _ in CORPUS:
        bank.add(text, id=qid)
    return bank


def eval_sequential(embedder) -> list[tuple[str, str, str, str]]:
    bank, rows = QuestionBank(embedder), []
    det = DuplicateDetector(bank)
    for qid, text, expected in CORPUS:
        v = det.check(text)
        rows.append((qid, expected, v.label, v.match_id or ""))
        bank.add(text, id=qid)
    return rows


def eval_held_out(embedder) -> list[tuple[str, str, str, str]]:
    det = DuplicateDetector(corpus_bank(embedder))
    return [(text, expected, (v := det.check(text)).label, v.match_id or "") for text, expected in HELD_OUT]


def metrics(rows) -> dict:
    is_dup = lambda label: label in ("exact_duplicate", "semantic_duplicate")
    flagged = lambda label: label != "unique"
    tp = sum(is_dup(e) and flagged(g) for _, e, g, _ in rows)
    fp = sum(not is_dup(e) and e != "needs_review" and flagged(g) for _, e, g, _ in rows)
    fn = sum(is_dup(e) and not flagged(g) for _, e, g, _ in rows)
    auto_fp = sum(not is_dup(e) and is_dup(g) for _, e, g, _ in rows)  # wrongly auto-rejected
    return {
        "label accuracy": sum(e == g for _, e, g, _ in rows) / len(rows),
        "dup recall (flagged)": tp / max(tp + fn, 1),
        "dup precision (flagged)": tp / max(tp + fp, 1),
        "unique questions wrongly auto-rejected": auto_fp,
    }


def synthetic_questions(n: int) -> list[str]:
    frames = ["What is {}?", "Define {}.", "State the laws of {}.", "Give two examples of {}.",
              "Why does {} occur?", "How is {} measured?", "What is the difference between {} and heat?"]
    topics = ["reflection", "refraction", "dispersion", "diffraction", "interference", "polarisation",
              "magnetism", "inertia", "friction", "momentum", "pressure", "buoyancy", "osmosis", "diffusion",
              "evaporation", "condensation", "photosynthesis", "respiration", "oxidation", "electrolysis"]
    qualifiers = ["", "light ", "sound ", "water ", "a metal ", "a gas ", "a liquid ", "the earth ",
                  "a plant ", "a cell ", "an ion ", "a wave ", "a magnet ", "an electron ", "a planet "]
    out = [f.format(q + t) for f, t, q in itertools.product(frames, topics, qualifiers)]
    return out[:n]


def latency(embedder, n: int = 2000) -> dict:
    bank = QuestionBank(embedder)
    t0 = time.perf_counter()
    bank.add_many([Question(t) for t in synthetic_questions(n)])
    index_s = time.perf_counter() - t0
    det = DuplicateDetector(bank)
    probes = ["What is reflection of light?", "Explain refraction in a glass slab.", "Define momentum."] * 10
    t0 = time.perf_counter()
    for p in probes:
        det.check(p)
    check_ms = (time.perf_counter() - t0) / len(probes) * 1000

    rng = np.random.default_rng(0)
    big = rng.standard_normal((100_000, 384)).astype(np.float32)
    big /= np.linalg.norm(big, axis=1, keepdims=True)
    q = big[0]
    t0 = time.perf_counter()
    for _ in range(20):
        sims = big @ q
        np.argpartition(-sims, 10)[:10]
    search_ms = (time.perf_counter() - t0) / 20 * 1000
    return {"bank size": len(bank), "index time (s)": round(index_s, 2),
            "check() latency (ms)": round(check_ms, 1), "top-10 search over 100k x 384 (ms)": round(search_ms, 1)}


def table(headers, rows) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    embedders = []
    try:
        embedders.append(SentenceTransformerEmbedder())
    except Exception as exc:
        print(f"sentence-transformers unavailable ({exc}); evaluating TF-IDF only")
    embedders.append(TfidfEmbedder())

    doc = ["# Question 2 - detector evaluation\n",
           "Generated by `python -m q2_duplicate_questions.evaluate`. Flagged = any non-`unique` verdict.\n"]
    for emb in embedders:
        seq, held = eval_sequential(emb), eval_held_out(emb)
        doc.append(f"## Embedder: `{emb.name}` (dup >= {emb.dup_threshold}, review >= {emb.review_threshold})\n")
        doc.append("### A. Section-6 corpus (each question vs. the ones before it)\n")
        doc.append(table(["id", "expected", "got", "matched", ""],
                         [(i, e, g, m, "ok" if e == g else "**MISS**") for i, e, g, m in seq]) + "\n")
        doc.append("### B. Held-out candidates vs. Q1-Q10\n")
        doc.append(table(["candidate", "expected", "got", "matched", ""],
                         [(t, e, g, m, "ok" if e == g else "**MISS**") for t, e, g, m in held]) + "\n")
        conf = Counter((e, g) for _, e, g, _ in seq + held)
        doc.append("### Confusion matrix (A + B; rows = expected, cols = got)\n")
        doc.append(table(["expected \\ got"] + LABELS,
                         [[e] + [conf[(e, g)] for g in LABELS] for e in LABELS]) + "\n")
        doc.append(table(["metric", "value"], [(k, f"{v:.2f}" if isinstance(v, float) else v)
                                               for k, v in metrics(seq + held).items()]) + "\n")
        doc.append("### C. Performance (CPU)\n")
        doc.append(table(["metric", "value"], list(latency(emb).items())) + "\n")

    out = Path("examples/q2")
    out.mkdir(parents=True, exist_ok=True)
    (out / "EVALUATION.md").write_text("\n".join(doc), encoding="utf-8")
    print("\n".join(doc))


if __name__ == "__main__":
    main()
