"""Run every Question 1 test scenario end to end and write examples/REPORT.md.

    python scripts/run_scenarios.py            # real detector (OWLv2) + LLM planner if a key is set
    IMGCAT_OFFLINE=1 python scripts/run_scenarios.py   # rule planner only

Creates a fresh catalog in runtime/scenario_catalog, then:
 1. adds every test image (auto-detection) and checks names/colours/boxes
 2. adds an object the detector missed
 3. edits name, colour, confidence and bbox of detected objects
 4. shows corrections survive re-detection and a restart until force=True
 5. composes "one red apple and one orange" from existing assets
 6. composes "a boy, a girl, and colored shapes"
 7. overlapping shapes, images with no objects, a failed detection,
    and a composite request for an asset the catalog lacks
"""
from __future__ import annotations

import json
import shutil
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from imgcat.composite import MissingAssetError  # noqa: E402
from imgcat.service import CatalogService, ProtectedObjectsError  # noqa: E402
from imgcat.viz import annotate  # noqa: E402

IMAGES = ROOT / "test_images"
EX = ROOT / "examples"
CAT = ROOT / "runtime" / "scenario_catalog"
TRUTH = json.loads((IMAGES / "ground_truth.json").read_text())

ORDER = ["apple", "orange", "boy", "girl", "shapes", "colors", "apple_orange", "overlapping_shapes",
         "blank", "noise", "camouflage", "truncated"]

lines: list[str] = []


def out(s: str = "") -> None:
    print(s)
    lines.append(s)


def iou(a, b) -> float:
    ax1, ay1, bx1, by1 = a["x"] + a["width"], a["y"] + a["height"], b["x"] + b["width"], b["y"] + b["height"]
    iw = max(0, min(ax1, bx1) - max(a["x"], b["x"]))
    ih = max(0, min(ay1, by1) - max(a["y"], b["y"]))
    inter = iw * ih
    return inter / (a["width"] * a["height"] + b["width"] * b["height"] - inter)


def objects_table(img) -> None:
    objs = img.to_dict()["objects"]
    if not objs:
        out("_no objects_")
        return
    out("| object | name | colour | confidence | bbox (x, y, w, h) | origin | user-edited fields | extra |")
    out("|---|---|---|---|---|---|---|---|")
    for o in objs:
        e = o["effective"]
        b = e["bbox"]
        a = e.get("attributes") or {}
        extra = []
        if a.get("clothing_colors"):
            extra.append("clothing: " + ", ".join(a["clothing_colors"]))
        if a.get("occluded"):
            extra.append(f"occluded by {', '.join(a.get('occluded_by') or [])} "
                         f"({a.get('visible_fraction', 0):.0%} visible)")
        if a.get("needs_review"):
            extra.append("needs review")
        conf = f"{e['confidence']:.2f}" if e.get("confidence") is not None else "-"
        out(f"| {e['display_name']} | {e['name']} | {e.get('color') or '-'} | {conf} | "
            f"{b['x']}, {b['y']}, {b['width']}, {b['height']} | {o['origin']} | "
            f"{', '.join(o['edited_fields']) or '-'} | {'; '.join(extra) or '-'} |")


def save_annotated(svc, img, name) -> str:
    rel = f"annotated/{name}.png"
    annotate(svc.store.image_path(img.id), img.to_dict()["objects"], EX / rel)
    return rel


def check_truth(img, name) -> None:
    gt = TRUTH.get(name)
    if gt is None:
        return
    objs = [o["effective"] for o in img.to_dict()["objects"]]
    if not gt:
        out(f"Ground truth: no objects → detected {len(objs)} {'✅' if not objs else '❌'}")
        return
    rows = []
    for g in gt:
        best = max(objs, key=lambda e: iou(e["bbox"], g["bbox"]), default=None)
        if best is None:
            rows.append(f"{g['name']} ❌ missed")
            continue
        ok_name = g["name"] in (best["name"], best["display_name"]) or g["name"].endswith(best["name"])
        ok_color = g["color"] == best.get("color")
        label = g["name"] if g["name"].startswith(g["color"]) else f"{g['color']} {g['name']}"
        rows.append(f"{label}: IoU {iou(best['bbox'], g['bbox']):.3f}, "
                    f"name {'✅' if ok_name else '❌'}, colour {'✅' if ok_color else '❌'}")
    out("Ground-truth check: " + " · ".join(rows))


def main() -> None:
    shutil.rmtree(CAT, ignore_errors=True)
    for sub in ("annotated", "composites"):
        shutil.rmtree(EX / sub, ignore_errors=True)
        (EX / sub).mkdir(parents=True, exist_ok=True)
    svc = CatalogService(CAT)
    out("# Question 1 — scenario run")
    out()
    out(f"Detector: `{svc.detector.version}` · generated by `scripts/run_scenarios.py` on "
        f"{time.strftime('%Y-%m-%d %H:%M')}")
    out()

    # ---------------------------------------------------------------- 1
    out("## Scenario 1 — automatic detection (names, colours, confidence, boxes)")
    out()
    ids = {}
    for name in ORDER:
        t = time.time()
        img = svc.add_image(IMAGES / f"{name}.png", display_name=name)
        ids[name] = img.id
        if name in ("blank", "noise", "camouflage", "truncated"):
            continue  # reported under scenario 7 / 2
        out(f"### `{name}` — status **{img.detection_status}**, style {img.style}, "
            f"{img.width}×{img.height}, {time.time() - t:.1f}s")
        out()
        objects_table(img)
        out()
        check_truth(img, name)
        out()
        out(f"![{name}]({save_annotated(svc, img, name)})")
        out()

    # ---------------------------------------------------------------- 2
    out("## Scenario 2 — manually add an object the detector missed")
    out()
    cam = svc.get(ids["camouflage"])
    out(f"`camouflage` hides a square that is only ~6 grey levels brighter than its textured background. "
        f"Detection status: **{cam.detection_status}** with {len(cam.live_objects)} objects "
        f"(note: {cam.detection_error}; OWLv2 finds nothing above threshold).")
    out()
    added = svc.add_object(cam.id, "square", {"x": 320, "y": 220, "width": 160, "height": 160}, color="gray",
                           confidence=1.0, notes="low-contrast patch the detector missed")
    cam = svc.get(cam.id)
    out(f"User adds `square` → object `{added.id}` origin `{added.origin}`, image objects_source "
        f"**{cam.objects_source}**.")
    out()
    objects_table(cam)
    out()
    out(f"![camouflage]({save_annotated(svc, cam, 'camouflage_corrected')})")
    out()

    # ---------------------------------------------------------------- 3
    out("## Scenario 3 — edit name, colour, confidence and bounding box")
    out()
    ao = svc.get(ids["apple_orange"])
    apple = next(o for o in ao.live_objects if o.effective["name"] == "apple")
    orange = next(o for o in ao.live_objects if o.effective["name"] == "orange")
    before = dict(apple.effective)
    b = apple.effective["bbox"]
    svc.update_object(apple.id, display_name="Gala apple", confidence=1.0,
                      bbox={"x": b["x"] - 4, "y": b["y"] - 4, "width": b["width"] + 8, "height": b["height"] + 8})
    svc.update_object(orange.id, name="mandarin", color="orange")
    apple, orange = svc.store.get_object(apple.id), svc.store.get_object(orange.id)
    out("| field | detector value (`auto`, read-only) | user override (`user`) | effective |")
    out("|---|---|---|---|")
    for f in ("display_name", "confidence", "bbox"):
        out(f"| apple.{f} | {before.get(f)} | {apple.user.get(f, '-')} | {apple.effective.get(f)} |")
    out(f"| orange.name | {orange.auto['name']} | {orange.user.get('name')} | {orange.effective['name']} |")
    out()
    # remove a detection the user does not want
    colors = svc.get(ids["colors"])
    purple = next(o for o in colors.live_objects if o.effective["color"] == "purple")
    svc.delete_object(purple.id)
    colors = svc.get(ids["colors"])
    out(f"Deleted the purple swatch from `colors` → {len(colors.live_objects)} live objects "
        f"(detector objects are tombstoned with `user.deleted = true`, so a later run can't bring them back silently).")
    out()
    ao = svc.get(ids["apple_orange"])
    objects_table(ao)
    out()
    out(f"![apple_orange corrected]({save_annotated(svc, ao, 'apple_orange_corrected')})")
    out()

    # ---------------------------------------------------------------- 4
    out("## Scenario 4 — corrections persist until detection is explicitly re-run")
    out()
    try:
        svc.run_detection(ids["apple_orange"])
        out("❌ re-detection was allowed")
    except ProtectedObjectsError as exc:
        out(f"`run_detection(apple_orange)` → **refused**: _{exc}_")
    out()
    svc2 = CatalogService(CAT, detector=svc.detector)  # simulate a restart: new connection, same files
    ao2 = svc2.get(ids["apple_orange"])
    names = sorted(o.effective["display_name"] for o in ao2.live_objects)
    out(f"After restart: objects_source **{ao2.objects_source}**, objects {names}, "
        f"purple swatch still deleted: {all(o.effective['color'] != 'purple' for o in svc2.get(ids['colors']).live_objects)}")
    out()
    forced = svc2.run_detection(ids["apple_orange"], force=True)
    runs = svc2.store.runs(ids["apple_orange"])
    out(f"`run_detection(apple_orange, force=True)` → objects_source **{forced.objects_source}**, objects "
        f"{sorted(o.effective['display_name'] for o in forced.live_objects)}. Detection history has "
        f"{len(runs)} runs; the forced run archived {len(json.loads(runs[-1]['replaced']))} replaced objects "
        f"(including the user's edits) in `detection_runs.replaced`.")
    out()
    svc = svc2

    # ---------------------------------------------------------------- 5 & 6
    composites = [
        ("5", "Create an image containing one red apple and one orange", "apple_and_orange"),
        ("6", "Create an image containing a boy, a girl, and colored shapes", "boy_girl_shapes"),
        ("6b", "Overlapping red circle, blue square and green triangle on a yellow background", "overlap_layers"),
    ]
    for num, instruction, fname in composites:
        out(f"## Scenario {num} — composite: “{instruction}”")
        out()
        t = time.time()
        comp = svc.compose(instruction, display_name=fname, verify=True)
        prov = comp.to_dict()["auto"]["provenance"]
        shutil.copyfile(svc.store.image_path(comp.id), EX / "composites" / f"{fname}.png")
        out(f"Planner: `{prov['plan']['planner']}` · layout `{prov['plan']['layout']}` · "
            f"{comp.width}×{comp.height} · {time.time() - t:.1f}s · new catalog entry `{comp.id}` "
            f"(kind **{comp.kind}**, objects_source **{comp.objects_source}**)")
        out()
        out("| placed object | source image | source bbox | mask | scale | placed bbox | z |")
        out("|---|---|---|---|---|---|---|")
        for p in prov["placements"]:
            o = svc.store.get_object(p["object_id"]).effective
            sb, pb = p["source_bbox"], p["bbox"]
            out(f"| {o['display_name']} | `{p['source_image']}` | {sb['x']},{sb['y']},{sb['width']},{sb['height']} | "
                f"{p['mask_source']} | {p['scale']} | {pb['x']},{pb['y']},{pb['width']},{pb['height']} | {p['z_index']} |")
        out()
        v = prov.get("verification")
        if v:
            out(f"Self-check (detector re-run on the composite): all placed objects found = **{v['all_found']}** — " +
                ", ".join(f"{f['placed']}→{f['detected_as']} (IoU {f['iou']})" for f in v["objects"]))
            out()
        out(f"![{fname}](composites/{fname}.png)")
        out()

    out("### Missing asset — no silent substitution")
    out()
    try:
        svc.compose("Create an image containing an apple and a banana")
        out("❌ composite was produced")
    except MissingAssetError as exc:
        out(f"`compose('an apple and a banana')` → **MissingAssetError**: _{exc}_")
    out()

    # ---------------------------------------------------------------- 7
    out("## Scenario 7 — overlapping objects, no detectable objects, failures")
    out()
    ov = svc.get(ids["overlapping_shapes"])
    out(f"`overlapping_shapes`: {len(ov.live_objects)} objects, overlapping boxes, occlusion order recovered "
        "(see scenario 1 table). Pairwise IoU of the detected boxes: " +
        ", ".join(f"{a.effective['display_name']}/{b.effective['display_name']} {iou(a.effective['bbox'], b.effective['bbox']):.2f}"
                  for i, a in enumerate(ov.live_objects) for b in ov.live_objects[i + 1:]))
    out()
    for name in ("blank", "noise", "truncated"):
        img = svc.get(ids[name])
        out(f"- `{name}` → status **{img.detection_status}**, {len(img.live_objects)} objects"
            + (f", error: `{img.detection_error}`" if img.detection_error else ""))
    out()
    out("`no_objects` is a successful run that found nothing; `failed` means the run itself broke "
        "(here a truncated PNG). In both cases the user can add objects manually as in scenario 2.")
    out()

    export = {img.to_dict()["user"]["display_name"]: img.to_dict(include_deleted=True) for img in svc.store.list_images()}
    (EX / "catalog_export.json").write_text(json.dumps(export, indent=2, default=str))
    (EX / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {EX / 'REPORT.md'}")


if __name__ == "__main__":
    main()
