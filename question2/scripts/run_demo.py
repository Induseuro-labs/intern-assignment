"""End-to-end demonstration for Question 2; writes examples/REPORT.md.

    python scripts/run_demo.py              # uses the LLM (OpenRouter) when a key is configured
    QGEN_OFFLINE=1 python scripts/run_demo.py   # detection parts only, no generation
"""
from __future__ import annotations

import json
import shutil
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from qgen import evaluate as E  # noqa: E402
from qgen.detector import DuplicateDetector  # noqa: E402
from qgen.generator import QuestionGenerator, naive_generate  # noqa: E402
from qgen.llm import GEN_LLM, llm_available  # noqa: E402
from qgen.pipeline import generate_and_store  # noqa: E402
from qgen.store import QuestionStore  # noqa: E402

EX = ROOT / "examples"
RUNTIME = ROOT / "runtime"
lines: list[str] = []
TOPIC = "Reflection of light (physics, grade 9-10)"


def out(s: str = "") -> None:
    print(s)
    lines.append(s)


def md(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def load_collection(path: Path) -> QuestionStore:
    store = QuestionStore(path)
    for q in E.load_corpus():
        if q["id"] != "Q10" and q["expected"] in ("original", "different"):  # keep the bank free of known dups
            store.add(q["text"], {**q["tags"], "set": "assignment-corpus"}, qid=q["id"])
    bank = json.loads((ROOT / "data" / "bank.json").read_text(encoding="utf-8"))["questions"]
    for i, q in enumerate(bank, 1):
        store.add(q["text"], q["tags"], qid=f"B{i:03d}")
    return store


def verdict_table(det, candidates) -> None:
    out("| candidate | verdict | matched question | why |")
    out("|---|---|---|---|")
    for kind, text in candidates:
        v = det.check(text)
        m = f"{v.matched_id}: {md(v.matched_text)}" if v.matched_id else "-"
        out(f"| {md(text)} <br>_({kind})_ | **{v.label}** | {m} | {md(v.reason)} |")
    out()


def main() -> None:
    llm = llm_available()
    shutil.rmtree(RUNTIME, ignore_errors=True)
    EX.mkdir(exist_ok=True)
    out("# Question 2 — demonstration run")
    out()
    out(f"Generated by `scripts/run_demo.py` on {time.strftime('%Y-%m-%d %H:%M')}. LLM: "
        f"{'`' + GEN_LLM + '` for generation, `anthropic/claude-haiku-5.5` as grey-zone judge' if llm else 'not configured'}.")
    out()

    # ------------------------------------------------------------- part 1
    out("## 1. Independent detection on the assignment corpus (Q1–Q10)")
    out()
    out("Each question is inserted in order and classified against the ones before it.")
    out()
    modes = [("offline (no LLM)", False)] + ([("with LLM judge", True)] if llm else [])
    results = {name: E.eval_corpus(flag) for name, flag in modes}
    head = "| ID | question | expected | " + " | ".join(n for n, _ in modes) + " | evidence (" + modes[-1][0] + ") |"
    out(head)
    out("|" + "---|" * (4 + len(modes)))
    for i, q in enumerate(E.load_corpus()):
        cells = []
        for name, _ in modes:
            r = results[name][i]
            cells.append(f"{'✅' if r['ok'] else '❌'} {r['label']}" + (f" → {r['matched']}" if r["matched"] else ""))
        last = results[modes[-1][0]][i]
        out(f"| {q['id']} | {md(q['text'])} | {q['expected']}{' of ' + q['of'] if q.get('of') else ''} | "
            + " | ".join(cells) + f" | {md(last['reason'])} |")
    for name, _ in modes:
        rows = results[name]
        out()
        out(f"**{name}:** {sum(r['ok'] for r in rows)}/{len(rows)} correct, "
            f"median {sorted(r['ms'] for r in rows)[len(rows) // 2]} ms per check")
    out()

    # ------------------------------------------------------------- part 2
    store = load_collection(RUNTIME / "demo.db")
    det = DuplicateDetector(store, use_llm=llm).build()
    out(f"## 2. Detection examples against the full collection ({store.count()} questions)")
    out()
    out("The collection is the 9 non-duplicate corpus questions plus a 140-question *Light* chapter bank "
        "(`data/bank.json`, generated once and committed). Candidates were written by hand to cover each case.")
    out()
    verdict_table(det, [
        ("exact – case/punctuation/spacing", "  WHAT IS REFLECTION OF LIGHT ?? "),
        ("exact – article dropped", "State laws of reflection of light"),
        ("exact – degree sign vs word", "The angle of incidence is 30 degrees. What is the angle of reflection?"),
        ("semantic – paraphrase", "What is meant by the reflection of light?"),
        ("semantic – paraphrase", "Explain what is meant by light reflection."),
        ("semantic – paraphrase of a bank question", "Why is the word AMBULANCE painted in mirror writing on the front of ambulances?"),
        ("semantic – reworded with same givens", "If the angle of incidence equals 30°, find the angle of reflection."),
        ("different – same subject, new concept", "Why do we see our reflection in a still lake but not in a rough sea?"),
        ("different – same numbers template, new values", "The angle of incidence is 55°. What is the angle of reflection?"),
        ("different – related but different answer", "What is the angle of incidence when a ray falls normally on a mirror?"),
        ("different – application", "How does a periscope use two plane mirrors to let a submarine crew see above water?"),
        ("ambiguous – broader wording", "What is reflection?"),
    ])

    # ------------------------------------------------------------- part 3
    out("## 3. Tags are metadata, not identity")
    out()
    keys = store.tag_keys()
    out(f"Tag keys present (free-form, added per question): {', '.join(f'`{k}`' for k in keys)}.")
    out()
    store.set_tags("Q5", {"bloom": "remember", "exam": ["CBSE-2023", "ICSE-2022"]})
    out(f"Added new keys at runtime to Q5 → {store.get('Q5').tags}")
    out()
    out(f"Filter `topic=reflection, difficulty=easy` → {len(store.all({'topic': 'reflection', 'difficulty': 'easy'}))} "
        f"questions; filter `exam=CBSE-2023` → {[q.id for q in store.all({'exam': 'CBSE-2023'})]}.")
    out()
    v1 = det.check("Define the reflection of light.")
    v2 = det.check("What is the critical angle?")
    out(f"- Same content as Q1 but would carry different tags (`chapter=optics`, `board=ICSE`) → **{v1.label}** of "
        f"{v1.matched_id}. Tags are never compared.")
    out(f"- Different content with the *same* tags as the bank's refraction questions → **{v2.label}**"
        + (f" ({v2.matched_id})" if v2.matched_id else "") + ".")
    out()

    # ------------------------------------------------------------- part 4
    if not llm:
        out("_Generation parts skipped: no LLM configured._")
    else:
        gen = QuestionGenerator(store)
        ctx, _, _ = gen.select_context(TOPIC)
        out("## 4. Generation with duplicate avoidance")
        out()
        out(f"**Context selection** for “{TOPIC}”: pool {ctx.pool_size} questions → {ctx.relevant} relevant "
            f"(cosine ≥ {gen.relevance_floor}) → **{len(ctx.concepts)} concepts** after clustering paraphrase "
            f"families → {ctx.shown} shown within a {gen.budget_tokens}-token budget (≈{ctx.est_tokens} tokens used).")
        out()
        big = [c for c in ctx.concepts if c.size > 1][:4]
        out("Largest concept clusters (each becomes one prompt line):")
        out()
        for c in big:
            out(f"- **{c.size}×** “{c.representative}” — also: " + "; ".join(f"“{m}”" for m in c.members if m != c.representative)[:300])
        out()
        out("<details><summary>Prompt context block sent to the LLM</summary>")
        out()
        out("```")
        out(ctx.prompt_block)
        out("```")
        out("</details>")
        out()
        n = 8
        # baseline is generated and checked first, against the same collection the workflow sees
        naive = naive_generate(TOPIC, n)
        nv = [det.check(q) for q in naive]
        report = generate_and_store(store, TOPIC, n, new_tags={"chapter": "light", "topic": "reflection",
                                                                 "generated_by": GEN_LLM}, generator=gen, detector=det)
        g = report.generation
        out(f"Asked for {n} questions; {g.rounds} round(s); {len(g.accepted)} passed the in-loop novelty filter, "
            f"{len(g.rejected)} were rejected and fed back to the next round.")
        out()
        out("| # | generated question | concept | in-loop novelty | independent detector | stored as |")
        out("|---|---|---|---|---|---|")
        for i, (c, v) in enumerate(zip(g.accepted, report.verdicts), 1):
            stored = "dropped" if v in report.dropped else ("needs_review" if v.label == "needs_review" else "active")
            out(f"| {i} | {md(c.question)} | {md(c.concept)} | max sim {c.similarity:.2f} | **{v.label}**"
                + (f" ({v.matched_id})" if v.matched_id else "") + f" | {stored} |")
        out()
        if g.rejected:
            out("Rejected during generation (prevention layer):")
            out()
            for c in g.rejected:
                out(f"- round {c.round}: “{c.question}” — {c.reason}; nearest: “{c.nearest}”")
            out()

        # ----------------------------------------------------------- part 5
        out("## 5. Does prevention help? Naive prompt vs this workflow")
        out()
        out("Baseline: the same LLM asked for 8 questions on the topic **without** the collection. "
            "The independent detector checks both batches against the same original collection.")
        out()
        out("| baseline question | detector verdict |")
        out("|---|---|")
        for q, v in zip(naive, nv):
            out(f"| {md(q)} | **{v.label}**" + (f" → {v.matched_id}: {md(v.matched_text)}" if v.matched_id else "") + " |")
        out()
        dup = {"exact_duplicate", "semantic_duplicate"}
        out(f"- Baseline: **{sum(v.label in dup for v in nv)}/{len(nv)}** duplicates, "
            f"{sum(v.label == 'needs_review' for v in nv)} for review.")
        out(f"- This workflow: **{len(report.dropped)}/{len(report.verdicts)}** duplicates, "
            f"{len(report.review)} for review.")
        out()

    # ------------------------------------------------------------- part 6
    out("## 6. Evaluation")
    out()
    out("Thresholds were calibrated on `data/calibration_pairs.json` (52 labelled pairs on refraction, "
        "photosynthesis, motion, electricity, acids, cells, mirrors); the reflection corpus above is held out.")
    out()
    for name, flag in modes:
        m = E.eval_pairs(flag)
        out(f"**Calibration pairs, {name}:** accuracy {m['accuracy']:.0%} ({m['n']} pairs), duplicate precision "
            f"{m['dup_precision']:.0%}, duplicate recall {m['dup_recall']:.0%}, true duplicates or review cases "
            f"wrongly passed as unique: {m['missed_as_unique']}, {m['ms_per_pair']} ms/pair.")
        out()
        out("| gold \\ predicted | " + " | ".join(E.LABELS) + " |")
        out("|---|" + "---|" * len(E.LABELS))
        for g_ in E.LABELS:
            out(f"| {g_} | " + " | ".join(str(m["confusion"][g_][p]) for p in E.LABELS) + " |")
        out()
        if m["errors"]:
            out("Errors: " + "; ".join(f"“{e['b']}” vs “{e['a']}” gold {e['gold']} → {e['pred']}" for e in m["errors"]))
            out()
    out("**Retrieval cost as the collection grows** (exact cosine top-10 over 384-d vectors, this laptop's CPU):")
    out()
    out("| questions | ms / query | index size |")
    out("|---|---|---|")
    for r in E.scale_benchmark():
        out(f"| {r['n']:,} | {r['ms_per_query']} | {r['index_mb']} MB |")
    out()
    (EX / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\nwrote", EX / "REPORT.md")


if __name__ == "__main__":
    main()
